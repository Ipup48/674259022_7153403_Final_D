const seedDatabase = async () => {
  try {
    console.log('🔄 กำลังเชื่อมต่อฐานข้อมูล SQLite...');
    await sequelize.authenticate();
    console.log('✅ เชื่อมต่อฐานข้อมูลสำเร็จ');

    console.log('🔄 กำลังซิงค์ตารางฐานข้อมูล (force: true)...');
    await sequelize.sync({ force: true });

    console.log(`🔄 กำลังเพิ่มข้อมูลตัวอย่างกิจกรรมจำนวน ${initialEvents.length} รายการ...`);
    await Event.bulkCreate(initialEvents);

    console.log('🎉 เติมข้อมูลเริ่มต้น (Seed Data) สำเร็จเรียบร้อยแล้ว!');
    console.log('📋 สรุปรายการข้อมูลกิจกรรม:');
    const count = await Event.count();
    console.log(`- จำนวนทั้งหมด: ${count} รายการ`);
    console.log('- หมวดหมู่อบรม, สัมมนา, จิตอาสา ครบถ้วน');
    console.log('- มีทั้งสถานะเผยแพร่ (true) และฉบับร่าง (false)');
    
    process.exit(0);
  } catch (error) {
    console.error('❌ เกิดข้อผิดพลาดในการทำ Seeder:', error);
    process.exit(1);
  }
};

seedDatabase();
